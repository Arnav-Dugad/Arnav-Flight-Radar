// Airline logos and representative aircraft photos from Wikidata / Wikimedia Commons.
//
//  • Every file is freely licensed or public domain (Commons hosts nothing else); the
//    licence and author travel with each item and are shown next to it.
//  • Logos identify the operator (or aircraft manufacturer) only; trademarks belong to
//    their owners.
//  • "Representative" photos show the TYPE (and, where available, the airline's
//    livery) — never claimed to be the specific airframe. Exact-airframe photos
//    would need a real aircraft — every flight here is simulated.
// The table is generated by `npm run data:media` (scripts/build-media.mjs). Logos
// (airline wordmarks, square airline icons, manufacturer logos) are copied to this site.

import { useQuery } from '@tanstack/react-query';

/** [thumbnail URL, Commons file title, licence short name, author (plain text)] */
type Row = [string, string, string, string];

/**
 * How a logo sits on a background (from build-time pixel analysis): 'dark' = dark ink on
 * transparency (needs a light tile on dark UI), 'light' = white ink on transparency
 * (needs a dark tile on light UI), 'opaque' = draws its own background.
 */
export type LogoTone = 'dark' | 'light' | 'opaque';

export interface MediaItem {
  src: string;
  page: string;
  /** What the file shows, from its Commons title (e.g. "British Airways Boeing 777-236ER G-VIIH"). */
  caption: string;
  license: string;
  artist?: string;
  /** Logos only: see LogoTone (undefined = colourful, fine on any background). */
  tone?: LogoTone;
}

export interface MediaTable {
  logos: Record<string, Row>;
  /** Square airline icons / tail marks (media.json v2+). */
  icons?: Record<string, Row>;
  /** Aircraft-manufacturer logos keyed by the exact `maker` string of typeSpecs (v2+). */
  makers?: Record<string, Row>;
  /** Logo tones per table (v2+); keys without a tone are colourful logos. */
  tones?: { logos?: Record<string, LogoTone>; icons?: Record<string, LogoTone>; makers?: Record<string, LogoTone> };
  types: Record<string, Row>;
  liveries: Record<string, Row>;
}

let table: Promise<MediaTable> | null = null;

/**
 * Bump when media.json changes shape or gains tables: the service worker answers /data/*
 * stale-while-revalidate, so a new URL is what makes returning visitors get the new table
 * (and the maker logos) on their next load rather than the one after.
 */
const MEDIA_VERSION = 3;

export function loadMedia(): Promise<MediaTable> {
  table ??= fetch(`/data/media.json?v=${MEDIA_VERSION}`)
    .then((r) => {
      if (!r.ok) throw new Error(`HTTP ${r.status}`);
      return r.json() as Promise<MediaTable>;
    })
    .catch((e) => {
      table = null;
      throw e;
    });
  return table;
}

/**
 * Logos are self-hosted (copied at build time, `?v=<content hash>` so replaced files get
 * new URLs); photos load from Wikimedia's thumbnail hosts.
 */
export const mediaUrlOk = (u: string) => {
  if (/^\/media\/(logos\/(icons\/)?[A-Z0-9]{3}|makers\/[a-z0-9-]+)\.(png|jpg)(\?v=[0-9a-f]{6,16})?$/.test(u)) return true;
  try {
    const url = new URL(u);
    return url.protocol === 'https:' && (url.hostname === 'upload.wikimedia.org' || url.hostname === 'thumb.wikimedia.org');
  } catch {
    return false;
  }
};

function item(r: Row | undefined, tone?: LogoTone): MediaItem | undefined {
  if (!r || !mediaUrlOk(r[0])) return undefined;
  const m: MediaItem = {
    src: r[0],
    page: commonsPage(r[1]),
    license: r[2],
    caption: cleanTitle(r[1]),
  };
  if (r[3]) m.artist = r[3];
  if (tone) m.tone = tone;
  return m;
}

/** The Commons description page of a file title. */
export function commonsPage(title: string): string {
  return `https://commons.wikimedia.org/wiki/${encodeURIComponent(title.replace(/ /g, '_')).replace(/%3A/gi, ':')}`;
}

/** Turn a Commons file title into a readable caption (drop prefix, extension, Flickr ids, airport/date clutter). */
export function cleanTitle(title: string): string {
  return title
    .replace(/^File:/, '')
    .replace(/\.(jpe?g|png|gif|tiff?|webp|svg)$/i, '')
    .replace(/\s*\(\d{6,}\)\s*/g, ' ')
    .replace(/\s*-\s*Flickr\s*-.*$/i, '')
    .replace(/_/g, ' ')
    .replace(/\s{2,}/g, ' ')
    .trim();
}

export function useMediaTable() {
  return useQuery({ queryKey: ['media'], queryFn: loadMedia, staleTime: Infinity, gcTime: Infinity, retry: 1 });
}

export function airlineLogo(t: MediaTable | undefined, icao: string | undefined): MediaItem | undefined {
  return icao ? item(t?.logos[icao], t?.tones?.logos?.[icao]) : undefined;
}

/** Square airline icon (tail mark) for compact badges, when Wikidata has one. */
export function airlineIcon(t: MediaTable | undefined, icao: string | undefined): MediaItem | undefined {
  return icao ? item(t?.icons?.[icao], t?.tones?.icons?.[icao]) : undefined;
}

/** Logo of an aircraft manufacturer (key: the exact `maker` string, e.g. 'Airbus'). */
export function makerLogo(t: MediaTable | undefined, maker: string | undefined): MediaItem | undefined {
  return maker ? item(t?.makers?.[maker], t?.tones?.makers?.[maker]) : undefined;
}

/** Aircraft families whose members look alike in an airline's livery (closest first). */
const FAMILIES: string[][] = [
  ['A20N', 'A320', 'A21N', 'A321', 'A319', 'A318'],
  ['B38M', 'B738', 'B39M', 'B739', 'B37M', 'B737'],
  ['B752', 'B753'],
  ['B763', 'B762', 'B764'],
  ['B77W', 'B772', 'B77L'],
  ['B789', 'B788', 'B78X'],
  ['A333', 'A332', 'A339'],
  ['A359', 'A35K'],
  ['B748', 'B744'],
  ['E75L', 'E170', 'E190', 'E195', 'E295'],
  ['CRJ9', 'CRJ7', 'CRJ2'],
  ['AT76', 'AT45'],
  ['BCS3', 'BCS1'],
];

/** Best representative photo: the airline's livery on this type, else the type itself. */
export function representativePhoto(
  t: MediaTable | undefined,
  type: string | undefined,
  airlineIcao: string | undefined,
): (MediaItem & { kind: 'livery' | 'type' }) | undefined {
  if (!t || !type) return undefined;
  const livery = airlineIcao ? item(t.liveries[`${airlineIcao}|${type}`]) : undefined;
  if (livery) return { ...livery, kind: 'livery' };
  // The same airline on a sibling type (its 737-800 for a 737 MAX 8) beats another
  // airline's livery; the caption still names exactly what is pictured.
  if (airlineIcao) {
    const family = FAMILIES.find((f) => f.includes(type));
    for (const sib of family ?? []) {
      const s = sib === type ? undefined : item(t.liveries[`${airlineIcao}|${sib}`]);
      if (s) return { ...s, kind: 'livery' };
    }
  }
  const generic = item(t.types[type]);
  return generic ? { ...generic, kind: 'type' } : undefined;
}
